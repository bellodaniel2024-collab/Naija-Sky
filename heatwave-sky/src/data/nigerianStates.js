/**
 * Flat list of searchable Nigerian locations (cities + states)
 */
export const NIGERIAN_CITIES = NIGERIAN_STATES.flatMap(state =>
  state.majorCities.map(city => ({
    name: city,
    state: state.name,
    stateId: state.id,
    stateSlug: state.slug,
    country: 'Nigeria',
    lat: state.lat + (Math.random() - 0.5) * 0.5,
    lon: state.lon + (Math.random() - 0.5) * 0.5,
    type: 'city'
  }))
)

/**
 * Get state by slug
 */
export function getStateBySlug(slug) {
  return NIGERIAN_STATES.find(s => s.slug === slug || s.id === slug) || null
}

/**
 * Get state by name (case-insensitive)
 */
export function getStateByName(name) {
  const lower = name.toLowerCase()
  return NIGERIAN_STATES.find(s =>
    s.name.toLowerCase() === lower ||
    s.capital.toLowerCase() === lower
  ) || null
}

